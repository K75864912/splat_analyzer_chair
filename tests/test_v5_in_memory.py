class Renderer:
    device='mock';name='mock'
    def prepare(self,arrays):return arrays
    def render_rgb(self,g,w2c,K,w,h):
        out=[]
        for pose in w2c.a:
            i=int(round(-pose[0,3]));a=np.zeros((h,w,3),np.uint8);a[:]=[i,100,200];out.append(a)
