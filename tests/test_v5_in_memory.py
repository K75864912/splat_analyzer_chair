class V5Tests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory(prefix='v5_repo_test_');self.root=Path(self.temp.name)
        self.env=patch.dict(os.environ,{'SPLAT_POSITION_MODE':'mask','SPLAT_POST_NMS_IOU':'0.60',
            'SPLAT_CLUSTER_EPS_FRAC':'0.09','SPLAT_SAVE_FRAMES':'0','SPLAT_VERBOSE_DETECTIONS':'0'})
        self.env.start();Model.chunks=[]
        self.ren=load_functions(ROOT/'render_cameras.py',{'render_views','_write_frame','_depth_to_vis'},renderer_namespace())
        self.pipe=load_functions(ROOT/'pipeline.py',PIPE_FUNCTIONS|{'_predictor_head_end2end','_env_flag'},
                                 pipeline_namespace(self.ren['render_views']))
        self.golden=json.loads((Path(__file__).parent/'fixtures/v5_f_combined_synthetic.json').read_text())
    def tearDown(self):
        self.env.stop();self.temp.cleanup()
    def run_pipeline(self,path,**kwargs):
        with redirect_stdout(io.StringIO()) as log:
            result=self.pipe['run_pipeline']('synthetic.ply','chair',str(path),Config(),**kwargs)
        return result,log.getvalue()
    def compare_output(self,path,objects):
        self.assertEqual(normalize(objects),self.golden['objects'])
        for name in OUTPUTS:self.assertEqual(json.loads((path/name).read_text()),self.golden['outputs'][name],name)

    def test_default_matches_tested_F_without_frame_files(self):
        # Catch accidental preview/encoding work, even if no file reaches disk.
        self.ren['_write_frame']=lambda *a:(_ for _ in ()).throw(AssertionError('Unexpected frame write'))
        self.ren['_depth_to_vis']=lambda *a:(_ for _ in ()).throw(AssertionError('Unexpected preview conversion'))
        out=self.root/'memory';result,log=self.run_pipeline(out)
        self.compare_output(out,result)
        self.assertEqual(list((out/'frames').iterdir()),[])
        self.assertEqual(Model.chunks,[32,3])
        self.assertNotIn('  [detect] chair ',log)

    def test_debug_exports_and_logs_preserve_results(self):
        out=self.root/'debug';result,log=self.run_pipeline(out,save_frames=True,verbose_detections=True)
        self.compare_output(out,result)
        self.assertEqual(len(list((out/'frames').iterdir())),105)
        self.assertIn('  [detect] chair ',log)

    def test_legacy_renderer_and_file_detection(self):
        out=self.root/'legacy'
        with redirect_stdout(io.StringIO()):
            path=self.ren['render_views']('synthetic.ply',str(out),Config())
            raw=self.pipe['_run_yoloe_26'](out/'frames',['chair'],json.loads(Path(path).read_text()),2.)
        self.assertIsInstance(path,str)
        self.assertEqual(len(list((out/'frames').iterdir())),105)
        self.assertEqual(normalize(raw),self.golden['raw_detections'])

    def test_each_job_has_its_own_cache_and_releases_it(self):
        caches=[];original=self.pipe['render_cameras'].render_views
        def capture(*a,**kw):
            caches.append(kw['frame_cache'])
            return original(*a,**kw)
        self.pipe['render_cameras'].render_views=capture
        for i in range(2):
            out=self.root/f'job{i}';result,_=self.run_pipeline(out);self.compare_output(out,result)
        self.assertIsNot(caches[0],caches[1])
        self.assertEqual(caches,[{},{}])

    def test_cache_cleanup_after_render_or_detection_error(self):
        for stage in ['render','detect']:
            with self.subTest(stage=stage):
                caches=[];real_render=self.ren['render_views'];real_detect=self.pipe['_run_yoloe_26']
                def render(*a,**kw):
                    caches.append(kw['frame_cache'])
                    if stage=='render':
                        kw['frame_cache'][0]=(np.ones((1,1,3)),np.ones((1,1)))
                        raise RuntimeError('render failure')
                    return real_render(*a,**kw)
                def detect(*a,**kw):raise RuntimeError('detect failure')
                self.pipe['render_cameras'].render_views=render
                self.pipe['_run_yoloe_26']=detect
                with self.assertRaisesRegex(RuntimeError,stage+' failure'):
                    self.run_pipeline(self.root/stage)
                self.assertEqual(caches,[{}])
                self.pipe['_run_yoloe_26']=real_detect

    def test_incomplete_cache_fails_instead_of_skipping_frames(self):
        out=self.root/'incomplete';cache={}
        with redirect_stdout(io.StringIO()):
            path=self.ren['render_views']('synthetic.ply',str(out),Config(),frame_cache=cache,save_frames=False)
            del cache[2]
            with self.assertRaisesRegex(RuntimeError,'Missing in-memory RGB/depth for frame 2'):
                self.pipe['_run_yoloe_26'](out/'frames',['chair'],json.loads(Path(path).read_text()),2.,frame_cache=cache)

    def test_flat_nonzero_preserves_original_position_math(self):
        source=ast.get_source_segment((ROOT/'pipeline.py').read_text(),next(n for n in ast.parse((ROOT/'pipeline.py').read_text()).body if isinstance(n,ast.FunctionDef) and n.name=='_mask_world_position'))
        original=source.replace('    _nonzero_flat_idx = np.nonzero(valid.ravel(order="C"))[0]\n    y, x = np.divmod(_nonzero_flat_idx, valid.shape[1])\n    del _nonzero_flat_idx','    y, x = np.nonzero(valid)')
        ns={'np':np};exec(original,ns)
        rng=np.random.default_rng(7)
        for h,w in [(0,0),(1,1),(13,17),(65,71)]:
            d=rng.uniform(0,4,(h,w));m=rng.random((h,w))>.5
            if h*w>10:d.ravel()[:4]=[np.nan,np.inf,0,.01]
            for mask,depth in [(m,d),(m.T,d.T),(m[:,::-1],d[:,::-1]),(np.asfortranarray(m),np.asfortranarray(d))]:
                a=ns['_mask_world_position'](mask,depth,np.eye(3),np.eye(4))
                b=self.pipe['_mask_world_position'](mask,depth,np.eye(3),np.eye(4))
                self.assertEqual(normalize(a),normalize(b))

    def test_gpu_rgb_quantization_matches_cpu_contract_with_tensor_stub(self):
        torch=NS(uint8=np.uint8,cuda=NS(is_available=lambda:True),device=lambda s:s)
        rng=np.random.default_rng(5)
        boundaries=np.arange(256,dtype=np.float32)/255
        values=np.r_[boundaries,np.nextafter(boundaries,np.float32(0)),np.nextafter(boundaries,np.float32(2))]
        array=np.r_[values,rng.uniform(-1,2,768).astype(np.float32)].reshape(2,16,16,3)
        ns=dict(np=np,torch=torch,Renderer=object,NEAR_PLANE=.01,FAR_PLANE=1000.,SH_C0=.28209479177387814,
                rasterization=lambda **kw:(Tensor(array),None,{}))
        load_functions(ROOT/'renderers/gsplat_backend.py',{'GsplatRenderer'},ns)
        g={k:None for k in ['means','quats','scales','opacities','sh']};g['sh_degree']=0
        got=ns['GsplatRenderer']().render_rgb(g,Tensor(np.stack([np.eye(4)]*2)),Tensor(np.eye(3)),16,16)
        want=(np.clip(array,0,1)*255).astype(np.uint8)
        np.testing.assert_array_equal(got,want)

