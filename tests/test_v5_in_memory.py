def load_functions(path,names,namespace):
    tree=ast.parse(Path(path).read_text(encoding='utf-8'))
    nodes=[n for n in tree.body if isinstance(n,(ast.FunctionDef,ast.ClassDef)) and n.name in names]
    if len(nodes)!=len(names):raise AssertionError('Missing source functions: '+str(names-{n.name for n in nodes}))
    exec(compile(ast.Module(body=nodes,type_ignores=[]),str(path),'exec'),namespace)
    return namespace

def normalize(value):
    return json.loads(json.dumps(value,default=lambda a:a.tolist()))

class Tensor:
    def __init__(self,a):self.a=np.asarray(a)
    @property
    def shape(self):return self.a.shape
    @property
    def dtype(self):return self.a.dtype
    def cpu(self):return self
    def numpy(self):return self.a
    def __len__(self):return len(self.a)
    def __getitem__(self,k):return Tensor(self.a[k])
    def __gt__(self,v):return Tensor(self.a>v)
    def element_size(self):return self.a.itemsize
    def contiguous(self):return self
    def clamp(self,a,b):return Tensor(np.clip(self.a,a,b))
    def mul(self,n):return Tensor(self.a*n)
    def to(self,dtype):return Tensor(self.a.astype(dtype))
    def unsqueeze(self,axis):return Tensor(np.expand_dims(self.a,axis))
    def expand(self,*shape):
        return Tensor(np.broadcast_to(self.a,tuple(a if n==-1 else n for a,n in zip(self.a.shape,shape))))

